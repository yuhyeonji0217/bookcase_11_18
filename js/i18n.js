let currentLanguage = localStorage.getItem(LANGUAGE_KEY) === 'ko' ? 'ko' : 'en';
function t(key, params = {}) {
  const template = TRANSLATIONS[currentLanguage][key] ?? TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
const GENRE_NAMES = {'미분류':'uncategorized','Uncategorized':'uncategorized','소설':'genreFiction','Fiction':'genreFiction','에세이':'genreEssay','Essay':'genreEssay','인문':'genreHumanities','Humanities':'genreHumanities','자기계발':'genreSelfHelp','Self-help':'genreSelfHelp','과학':'genreScience','Science':'genreScience'};
function displayGenre(name) { return GENRE_NAMES[name] ? t(GENRE_NAMES[name]) : name; }
function applyLanguage() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const node = Array.from(el.childNodes).find(child => child.nodeType === Node.TEXT_NODE);
    if (node) node.nodeValue = t(el.dataset.i18n);
    else if (!el.children.length) el.textContent = t(el.dataset.i18n);
  });
  for (const attribute of ['placeholder','aria-label','title']) {
    document.querySelectorAll('[data-i18n-' + attribute + ']').forEach(el => {
      el.setAttribute(attribute, t(el.getAttribute('data-i18n-' + attribute)));
    });
  }
  document.querySelectorAll('[data-language]').forEach(button => {
    button.classList.toggle('active', button.dataset.language === currentLanguage);
    button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
  });
  if (typeof renderGenreOptions === 'function') renderGenreOptions();
  if ($('book-genre-custom')) $('book-genre-custom').placeholder = t('newGenreOption');
  if ($('edit-genre-custom')) $('edit-genre-custom').placeholder = t('newGenreOption');
  if (typeof renderGenreSettings === 'function' && $('genre-dialog').open) renderGenreSettings();
  if (typeof renderDetail === 'function' && !$('detail-view').hidden) renderDetail();
  if (typeof renderOwner === 'function') renderOwner();
}
